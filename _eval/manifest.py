#!/usr/bin/env python3
"""
Engine manifest — which files belong to the engine (the method), and whether an instance changed them.

The engine is the public method repo. An instance is a workspace that pulls a tagged engine and adds
its own `_shared/` content and runs. Engine files are read-only in an instance: method fixes go
upstream, get tagged, and come back through `./pull-engine.sh <tag>`.

  python3 _eval/manifest.py build [ROOT]               engine: write ROOT/engine.manifest
  python3 _eval/manifest.py check [ROOT]               list engine files whose hash changed
  python3 _eval/manifest.py install SRC DST [--force]  copy engine SRC into instance DST

engine.manifest lines:
  version <tag>
  owned <sha256> <path>    engine-owned; overwritten on pull; must not be edited in an instance
  seed  <path>             starter file; copied only if missing, then belongs to the instance

No third-party modules. Runs on the stock macOS python3.
"""

from __future__ import annotations

import hashlib
import shutil
import sys
from pathlib import Path

MANIFEST = "engine.manifest"

# Engine-owned paths. A trailing "/" means every file under it.
OWNED = [
    "CLAUDE.md",
    "CONTEXT.md",
    "README.md",
    "RUNBOOK.md",
    "eval",
    "pull-engine.sh",
    "_template/",
    "_eval/",
    "_shared/operating-principles.md",
    "_shared/report-design-system.md",
    "_shared/report-content-schema.md",
    "99-vision-synthesis/CLAUDE.md",
    "99-vision-synthesis/CONTEXT.md",
    "100-report/CLAUDE.md",
    "100-report/CONTEXT.md",
    "101-prototype-handoff/CLAUDE.md",
    "101-prototype-handoff/CONTEXT.md",
]

# Never part of the engine, even under an owned folder.
EXCLUDE_PREFIXES = ["_eval/report/", "_eval/cases/"]
EXCLUDE_NAMES = {".DS_Store", "__pycache__"}

# Starter files: the instance fills these in and owns them from then on.
SEED = [
    "_shared/CONTEXT.md",
    "_shared/product-context.md",
    "_shared/house-view.md",
    "_shared/decision-log.md",
    "_shared/setup-questionnaire.md",
    "_shared/vision-principles.md",
    "_shared/prototype-target.md",
    "_shared/accelerator-brief.md",
    "_shared/timeline.md",
]


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def excluded(rel: str) -> bool:
    return any(rel.startswith(p) for p in EXCLUDE_PREFIXES) or \
        any(part in EXCLUDE_NAMES for part in rel.split("/"))


def owned_files(root: Path) -> list[str]:
    found: set[str] = set()
    for entry in OWNED:
        p = root / entry
        if entry.endswith("/"):
            if p.is_dir():
                for f in p.rglob("*"):
                    rel = f.relative_to(root).as_posix()
                    if f.is_file() and not excluded(rel):
                        found.add(rel)
        elif p.is_file():
            found.add(entry)
    return sorted(found)


def read_manifest(root: Path) -> tuple[str, dict[str, str], list[str]]:
    """Returns (version, {path: sha}, [seed paths]). Empty if there is no manifest."""
    path = root / MANIFEST
    version, owned, seed = "", {}, []
    if not path.is_file():
        return version, owned, seed
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split(maxsplit=2)
        if not parts or parts[0].startswith("#"):
            continue
        if parts[0] == "version" and len(parts) > 1:
            version = parts[1]
        elif parts[0] == "owned" and len(parts) == 3:
            owned[parts[2]] = parts[1]
        elif parts[0] == "seed" and len(parts) > 1:
            seed.append(line.split(maxsplit=1)[1])
    return version, owned, seed


def build(root: Path, version: str = "") -> Path:
    lines = ["# Engine manifest. Generated by `python3 _eval/manifest.py build` — do not edit by hand.",
             f"version {version or 'untagged'}"]
    lines += [f"owned {sha(root / rel)} {rel}" for rel in owned_files(root)]
    lines += [f"seed {rel}" for rel in SEED if (root / rel).is_file()]
    out = root / MANIFEST
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def check(root: Path) -> list[tuple[str, str]]:
    """[(path, problem)] for every engine-owned file that no longer matches the manifest."""
    _, owned, _ = read_manifest(root)
    problems = []
    for rel, digest in owned.items():
        p = root / rel
        if not p.is_file():
            problems.append((rel, "deleted"))
        elif sha(p) != digest:
            problems.append((rel, "edited"))
    return problems


def install(src: Path, dst: Path, force: bool = False) -> int:
    if not (src / MANIFEST).is_file():
        print(f"no {MANIFEST} in {src} — is that an engine tag?", file=sys.stderr)
        return 2

    if (dst / MANIFEST).is_file() and not force:
        dirty = check(dst)
        if dirty:
            print("These engine files were changed in this instance. Pulling would overwrite them:",
                  file=sys.stderr)
            for rel, problem in dirty:
                print(f"  {problem:8} {rel}", file=sys.stderr)
            print("Move the change upstream to the engine first, or re-run with --force to discard it.",
                  file=sys.stderr)
            return 1

    _, old_owned, _ = read_manifest(dst)
    version, new_owned, seed = read_manifest(src)

    added = changed = removed = seeded = 0
    for rel in new_owned:
        s, d = src / rel, dst / rel
        if d.is_file() and sha(d) == sha(s):
            continue
        added += not d.exists()
        changed += d.exists()
        d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(s, d)

    # files the old engine owned and the new one dropped: delete them, so removals propagate
    for rel in old_owned:
        if rel not in new_owned and (dst / rel).is_file():
            (dst / rel).unlink()
            removed += 1

    for rel in seed:
        d = dst / rel
        if not d.exists():
            d.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src / rel, d)
            seeded += 1

    shutil.copy2(src / MANIFEST, dst / MANIFEST)
    print(f"engine {version}: {added} added · {changed} updated · {removed} removed · "
          f"{seeded} starter files seeded")
    return 0


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in ("build", "check", "install"):
        print(__doc__)
        return 2
    cmd, rest = argv[0], argv[1:]
    if cmd == "build":
        root = Path(rest[0]) if rest and not rest[0].startswith("--") else Path.cwd()
        version = next((a.split("=", 1)[1] for a in rest if a.startswith("--version=")), "")
        print(build(root.resolve(), version))
        return 0
    if cmd == "check":
        root = Path(rest[0]) if rest else Path.cwd()
        problems = check(root.resolve())
        for rel, problem in problems:
            print(f"{problem:8} {rel}")
        return 1 if problems else 0
    args = [a for a in rest if not a.startswith("--")]
    if len(args) != 2:
        print("usage: manifest.py install SRC DST [--force]", file=sys.stderr)
        return 2
    return install(Path(args[0]).resolve(), Path(args[1]).resolve(), "--force" in rest)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
